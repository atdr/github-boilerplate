"""scripts/audit-requirements.py, which turns uv exports into pip-audit input."""

from __future__ import annotations

import importlib.util
import subprocess
import sys
from pathlib import Path

import pytest

SCRIPT = Path(__file__).resolve().parent.parent / "scripts" / "audit-requirements.py"
_spec = importlib.util.spec_from_file_location("audit_requirements", SCRIPT)
assert _spec and _spec.loader
audit = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(audit)

HASH_A = "    --hash=sha256:" + "a" * 64
HASH_B = "    --hash=sha256:" + "b" * 64


def export(*lines: str) -> str:
    """A uv export: its header comment, then the given lines."""
    header = [
        "# This file was autogenerated by uv via the following command:",
        "#    uv export --locked --format requirements-txt --no-emit-local",
    ]
    return "\n".join(header + list(lines)) + "\n"


def run(tmp_path: Path, *texts: str) -> tuple[subprocess.CompletedProcess[str], dict[str, str]]:
    """Runs the script as the job does; returns the result and what it wrote."""
    exports = []
    for i, text in enumerate(texts):
        path = tmp_path / f"export-{i}.txt"
        path.write_text(text)
        exports.append(str(path))
    result = subprocess.run(
        [sys.executable, "-I", str(SCRIPT), str(tmp_path / "runtime"), *exports],
        capture_output=True,
        text=True,
        check=True,
    )
    written = {p.name: p.read_text() for p in sorted(tmp_path.glob("runtime-*.txt"))}
    return result, written


def test_keeps_each_requirement_with_its_continuation_hash_lines(tmp_path):
    text = export(
        "click==8.3.1 \\",
        HASH_A + " \\",
        HASH_B,
        "    # via demo",
        "idna==3.10 \\",
        HASH_A,
    )
    _, written = run(tmp_path, text)
    assert written == {
        "runtime-1.txt": f"click==8.3.1 \\\n{HASH_A} \\\n{HASH_B}\nidna==3.10 \\\n{HASH_A}\n"
    }


def test_drops_direct_url_requirements_with_a_notice(tmp_path):
    text = export(
        "certifi==2026.10.23 \\",
        HASH_A,
        "    # via requests",
        "requests @ git+https://github.com/psf/requests@b25c87d7cb8d6a18a37fa12442b5f883f9e41741",
        "    # via demo",
        "my-pkg[extra] @ https://example.com/my_pkg-1.0-py3-none-any.whl \\",
        HASH_B,
        "urllib3==2.8.0 \\",
        HASH_B,
    )
    result, written = run(tmp_path, text)
    # The URL lines go; their dependencies, separate lines of the export, stay.
    assert written == {"runtime-1.txt": f"certifi==2026.10.23 \\\n{HASH_A}\nurllib3==2.8.0 \\\n{HASH_B}\n"}
    notices = result.stdout.splitlines()
    assert len(notices) == 2
    assert notices[0].startswith("::notice title=Not audited::requests is a direct URL requirement of the runtime")
    assert notices[1].startswith("::notice title=Not audited::my-pkg is a direct URL requirement")
    # The URL can carry a token, so the notice names the package only.
    assert "github.com" not in result.stdout


def test_strips_environment_markers(tmp_path):
    # pip-audit skips a requirement whose marker is false on its own Python.
    text = export(
        "requests==2.25.0 ; python_full_version < '3.13' \\",
        HASH_A,
        "colorama==0.4.6 ; sys_platform == 'win32' \\",
        HASH_B,
        "idna==2.10;python_version<'3.13'",
    )
    _, written = run(tmp_path, text)
    assert written == {
        "runtime-1.txt": f"requests==2.25.0 \\\n{HASH_A}\ncolorama==0.4.6 \\\n{HASH_B}\nidna==2.10\n"
    }


def test_splits_several_versions_of_one_package_across_files(tmp_path):
    text = export(
        "click==8.3.1 \\",
        HASH_A,
        "idna==2.10 ; python_full_version < '3.13' \\",
        HASH_A,
        "idna==3.20 ; python_full_version >= '3.13' \\",
        HASH_B,
        "requests==2.25.0 ; python_full_version < '3.12' \\",
        HASH_A,
        "requests==2.31.0 ; python_full_version == '3.12.*' \\",
        HASH_B,
        "Requests==2.34.2 ; python_full_version >= '3.13' \\",
        HASH_B,
    )
    _, written = run(tmp_path, text)
    assert written == {
        "runtime-1.txt": f"click==8.3.1 \\\n{HASH_A}\nidna==2.10 \\\n{HASH_A}\nrequests==2.25.0 \\\n{HASH_A}\n",
        "runtime-2.txt": f"idna==3.20 \\\n{HASH_B}\nrequests==2.31.0 \\\n{HASH_B}\n",
        "runtime-3.txt": f"Requests==2.34.2 \\\n{HASH_B}\n",
    }


def test_keeps_one_version_once_across_markers_and_exports(tmp_path):
    first = export("certifi==2026.10.23 ; python_full_version < '3.13' \\", HASH_A)
    second = export("certifi==2026.10.23 \\", HASH_A, "pytest==9.2.0 \\", HASH_B)
    _, written = run(tmp_path, first, second)
    assert written == {"runtime-1.txt": f"certifi==2026.10.23 \\\n{HASH_A}\npytest==9.2.0 \\\n{HASH_B}\n"}


def test_writes_nothing_when_nothing_is_left_to_audit(tmp_path):
    # pip-audit refuses an empty requirements file.
    result, written = run(tmp_path, export())
    assert written == {} and result.stdout == ""
    result, written = run(tmp_path, export("requests @ git+https://github.com/psf/requests@v2.32.5"))
    assert written == {} and "::notice" in result.stdout


def test_blocks_ignores_comments_and_blank_lines_between_requirements():
    text = "# header\n\nclick==8.3.1 \\\n" + HASH_A + "\n    # via demo\n\n"
    assert audit.blocks(text) == [["click==8.3.1 \\", HASH_A]]


def selections(tmp_path: Path, pyproject: str | None) -> list[str]:
    path = tmp_path / "pyproject.toml"
    if pyproject is not None:
        path.write_text(pyproject)
    result = subprocess.run(
        [sys.executable, "-I", str(SCRIPT), "--selections", str(path)],
        capture_output=True,
        text=True,
        check=True,
    )
    return result.stdout.splitlines()


def test_selections_lists_each_extra_and_group_on_its_own(tmp_path):
    pyproject = """
[project]
name = "demo"
dependencies = ["click"]

[project.optional-dependencies]
old = ["requests==2.31.0"]
new = ["requests==2.34.2"]

[dependency-groups]
dev = ["pytest"]
docs = ["mkdocs"]

[tool.uv]
conflicts = [[{ extra = "old" }, { extra = "new" }]]
"""
    assert selections(tmp_path, pyproject) == [
        "--extra old",
        "--extra new",
        "--group dev",
        "--group docs",
    ]


def test_selections_includes_uvs_older_dev_dependencies(tmp_path):
    pyproject = '[project]\nname = "demo"\n\n[tool.uv]\ndev-dependencies = ["pytest"]\n'
    assert selections(tmp_path, pyproject) == ["--group dev"]


def test_selections_is_empty_without_extras_groups_or_pyproject(tmp_path):
    assert selections(tmp_path, '[project]\nname = "demo"\n') == []
    (tmp_path / "pyproject.toml").unlink()
    assert selections(tmp_path, None) == []


def member(root: Path, path: str, pyproject: str) -> None:
    (root / path).mkdir(parents=True)
    (root / path / "pyproject.toml").write_text(pyproject)


def test_selections_reaches_into_a_virtual_workspace(tmp_path):
    # A virtual root has no project, so its members hold the extras and
    # groups; uv exports each as `--package NAME --extra X` or `--group G`.
    root_pyproject = """
[tool.uv.workspace]
members = ["packages/*"]
exclude = ["packages/skip"]

[dependency-groups]
lint = ["ruff"]
"""
    member(
        tmp_path,
        "packages/a",
        '[project]\nname = "ws-a"\n\n[project.optional-dependencies]\nhttp = ["urllib3"]\n'
        '\n[dependency-groups]\ndev = ["pytest"]\n',
    )
    member(tmp_path, "packages/b", '[project]\nname = "ws-b"\n\n[dependency-groups]\ndocs = ["jinja2"]\n')
    member(tmp_path, "packages/skip", '[project]\nname = "ws-skip"\n\n[dependency-groups]\nx = ["certifi"]\n')
    (tmp_path / "packages/notes").mkdir()
    assert selections(tmp_path, root_pyproject) == [
        "--group lint",
        "--package ws-a",
        "--package ws-a --extra http",
        "--package ws-a --group dev",
        "--package ws-b",
        "--package ws-b --group docs",
    ]


def test_selections_leaves_a_workspace_root_project_to_its_own_lines(tmp_path):
    # The root project's own extras need no --package, and a members glob
    # matching it, or one member twice, adds nothing.
    root_pyproject = """
[project]
name = "Root_App"

[project.optional-dependencies]
cli = ["click"]

[tool.uv.workspace]
members = [".", "libs/*", "libs/core"]
"""
    member(tmp_path, "libs/core", '[project]\nname = "core"\n')
    assert selections(tmp_path, root_pyproject) == ["--extra cli", "--package core"]


def test_requires_an_output_prefix_and_an_export(tmp_path):
    result = subprocess.run([sys.executable, "-I", str(SCRIPT)], capture_output=True, text=True)
    assert result.returncode == 2 and result.stderr.startswith("Usage: ")


def test_falls_back_to_tomli_where_there_is_no_tomllib(tmp_path):
    # Python 3.10 has no tomllib; pip-audit, installed beside the script,
    # brings tomli. Simulated here: tomllib blocked, tomli standing in.
    (tmp_path / "pyproject.toml").write_text('[dependency-groups]\ndev = ["pytest"]\n')
    code = (
        "import runpy, sys, tomllib; sys.modules['tomli'] = tomllib; sys.modules['tomllib'] = None;"
        f" sys.argv = ['audit-requirements.py', '--selections', {str(tmp_path / 'pyproject.toml')!r}];"
        f" runpy.run_path({str(SCRIPT)!r}, run_name='__main__')"
    )
    result = subprocess.run([sys.executable, "-c", code], capture_output=True, text=True)
    assert result.returncode == 0, result.stderr
    assert result.stdout.splitlines() == ["--group dev"]


@pytest.mark.parametrize(
    ("install", "expected"),
    [
        ('pip install -e ".[dev]"', []),
        (
            'pip install --extra-index-url https://x.example/simple -e ".[dev]"',
            ["--extra-index-url", "https://x.example/simple"],
        ),
        (
            'pip install --index-url=https://x.example/simple -i "https://y.example/simple" -e .',
            ["--index-url=https://x.example/simple", "-i", "https://y.example/simple"],
        ),
        (
            "pip install -f /wheels --find-links='/w2' --trusted-host x.example --no-index -e .[*]",
            ["-f", "/wheels", "--find-links=/w2", "--trusted-host", "x.example", "--no-index"],
        ),
        # Quotes keep a path with a space in one piece, as the shell would.
        (
            'pip install --find-links "vendor/wheel cache" --find-links="a b" -e .',
            ["--find-links", "vendor/wheel cache", "--find-links=a b"],
        ),
        # Index options of a later command in the same input count too.
        (
            'pip install -e . && pip install --extra-index-url=https://z.example/simple tool',
            ["--extra-index-url=https://z.example/simple"],
        ),
        # Nothing is globbed, and a trailing option with no value is dropped.
        ("pip install * --extra-index-url", []),
    ],
)
def test_index_options_picks_only_index_options_out_of_install(tmp_path, install, expected):
    (tmp_path / "match-me").write_text("")
    result = subprocess.run(
        [sys.executable, "-I", str(SCRIPT), "--index-options", install],
        capture_output=True,
        text=True,
        check=True,
        cwd=tmp_path,
    )
    # NUL after each, so a value with a space survives the shell's read.
    assert result.stdout == "".join(option + "\0" for option in expected)
